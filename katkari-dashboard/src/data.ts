export function welfareScore(h: HH) {
  let s = 0;
  if (h.card === "Yes") s += 1;
  if (h.days > 0) s += 1;
  if (h.farm === "Yes") s += 1;
  if (h.shg === "Yes") s += 1;
  if (h.skill === "Yes") s += 1;
  if (h.assets !== "None") s += 1;
  if (h.needs !== "Not at all") s += 1;
  if (h.pmay !== "Never applied") s += 1;
  return s;
}
